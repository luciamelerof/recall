<?php
function normalizeAnswer(string $text): string
{
    $text = mb_strtolower($text, 'UTF-8');
    $text = strtr($text, [
        'á' => 'a', 'à' => 'a', 'ä' => 'a', 'â' => 'a',
        'é' => 'e', 'è' => 'e', 'ë' => 'e', 'ê' => 'e',
        'í' => 'i', 'ì' => 'i', 'ï' => 'i', 'î' => 'i',
        'ó' => 'o', 'ò' => 'o', 'ö' => 'o', 'ô' => 'o',
        'ú' => 'u', 'ù' => 'u', 'ü' => 'u', 'û' => 'u',
        'ñ' => 'n', 'ç' => 'c',
    ]);
    $text = preg_replace('/[^a-z0-9\s]/', '', $text);
    $text = preg_replace('/\s+/', ' ', $text);
    return trim($text);
}

function autoMark(string $given, string $expected): string
{
    $a = normalizeAnswer($given);
    $b = normalizeAnswer($expected);

    if ($a === '') return 'incorrect';
    if ($a === $b) return 'correct';

    $similarity = 1 - levenshtein($a, $b) / max(strlen($a), strlen($b));
    return $similarity >= 0.8 ? 'close' : 'incorrect';
}